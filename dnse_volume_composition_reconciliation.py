def load_canonical_trades(
    trades_dir: Path | str,
    session_date: str | None = None,
) -> pd.DataFrame:
    """Load canonical Trades from the materialization directory.

    Provenance: the generating code lives at
    ``CANONICAL_TRADES_SOURCE_COMMIT`` on a divergent worktree branch;
    the lineage status is ``CANONICAL_TRADES_LINEAGE_STATUS``.
    """
    trades_dir = Path(trades_dir)
    if session_date:
        path = trades_dir / f"session_date={session_date}" / "part-00000.parquet"
        if not path.exists():
            return pd.DataFrame()
        return pd.read_parquet(path)
    # Multi-session: read all session-date partitions
    frames = []
    for partition in sorted(trades_dir.glob("session_date=*")):
        p = partition / "part-00000.parquet"
        if p.exists():
            frames.append(pd.read_parquet(p))
    return pd.concat(frames, ignore_index=True) if frames else pd.DataFrame()


def extract_ohlc_daily_v(
    ohlc_dir: Path | str,
    symbol: str | None = None,
) -> pd.DataFrame:
    """Extract daily ``v`` from retained raw OHLC parquet files.

    Returns one row per (symbol, session_date) — deduplicated; earlier
    observation wins on exact duplicates.
    """
    ohlc_dir = Path(ohlc_dir)
    records: list[dict[str, Any]] = []

    files = list(ohlc_dir.glob("**/*.parquet"))
    if not files:
        return pd.DataFrame()

    for f in files:
        try:
            df = pd.read_parquet(f)
            for _, row in df.iterrows():
                inst = row.get("instrument")
                if symbol and inst != symbol:
                    continue
                payload = json.loads(row.get("raw_payload_json", "{}"))
                t_arr = payload.get("t", [])
                v_arr = payload.get("v", [])
                if not t_arr or not v_arr or len(t_arr) != len(v_arr):
                    continue
                dates = (
                    pd.to_datetime(t_arr, unit="s", utc=True)
                    .tz_convert(vn_time.VN_TZ)
                    .strftime("%Y-%m-%d")
                )
                for d, v in zip(dates, v_arr):
                    records.append(
                        {
                            "symbol": inst,
                            "session_date": d,
                            "daily_v": v,
                            "ohlc_observation_id": row.get("observation_id"),
                        }
                    )
        except Exception:  # noqa: BLE001  — retain partial results
            pass

    if not records:
        return pd.DataFrame()
    return (
        pd.DataFrame(records)
        .drop_duplicates(subset=["symbol", "session_date"], keep="first")
    )


# ---------------------------------------------------------------------------
# Core reconciliation engine
# ---------------------------------------------------------------------------

def reconcile_volume(
    trades_df: pd.DataFrame,
    ohlc_df: pd.DataFrame,
    *,
    c5_candidate: ScaledG1Candidate = C5_CANDIDATE,
    source_commit: str = CANONICAL_TRADES_SOURCE_COMMIT,
    lineage_status: str = CANONICAL_TRADES_LINEAGE_STATUS,
) -> pd.DataFrame:
    """Reconcile volume composition for every complete eligible symbol-session.

    Parameters
    ----------
    trades_df:
        Canonical Trades DataFrame with columns ``symbol``, ``session_date``,
        ``board_id``, ``quantity``.
    ohlc_df:
        OHLC DataFrame with columns ``symbol``, ``session_date``, ``daily_v``,
        ``ohlc_observation_id``.
    c5_candidate:
        The SCALED_G1 candidate contract.  Changing ``empirical_scale`` here
        produces a deterministic evaluation at a different scale without
        touching C1–C4 logic.
    source_commit, lineage_status:
        Provenance metadata recorded in every output row.

    Returns
    -------
    pd.DataFrame
        One row per eligible (symbol, session_date) intersection.
        - C1–C4 failures are NOT hidden; their delta and exact_match columns
          remain in every row unmodified.
        - C5 columns and residual_class are appended.
        - Provenance columns (source_commit, lineage_status) are appended.
        - ``qualified_liquidity_inputs`` is always False; C5 shadow validation
          does NOT promote volume authority.
    """
    if trades_df.empty or ohlc_df.empty:
        return pd.DataFrame()

    # Aggregate per (symbol, session_date, board_id)
    board_vols = (
        trades_df
        .groupby(["symbol", "session_date", "board_id"])["quantity"]
        .sum()
        .reset_index()
    )

    pivot_vols = board_vols.pivot_table(
        index=["symbol", "session_date"],
        columns="board_id",
        values="quantity",
        fill_value=0,
    ).reset_index()

    # Inner join: symbols absent from either side are excluded (never zero-filled)
    merged = pd.merge(ohlc_df, pivot_vols, on=["symbol", "session_date"], how="inner")

    results: list[dict[str, Any]] = []
    for _, row in merged.iterrows():
        symbol = row["symbol"]
        session_date = row["session_date"]
        daily_v = float(row["daily_v"])

        g1 = float(row.get("G1", 0) or 0)
        g4 = float(row.get("G4", 0) or 0)
        t1 = float(row.get("T1", 0) or 0)
        t3 = float(row.get("T3", 0) or 0)
        t4 = float(row.get("T4", 0) or 0)
        t6 = float(row.get("T6", 0) or 0)

        # ---- C1–C4 (preserved from P0-B.2A-B.2B) ----
        c1 = g1
        c2 = g1 + g4
        c3 = g1 + t1 + t3
        c4 = g1 + g4 + t1 + t3 + t4 + t6

        candidates_c1_c4 = {"C1": c1, "C2": c2, "C3": c3, "C4": c4}
        deltas_c1_c4 = {k: daily_v - v for k, v in candidates_c1_c4.items()}
        exact_c1_c4 = {k: d == 0.0 for k, d in deltas_c1_c4.items()}

        # ---- C5 (SCALED_G1 shadow candidate) ----
        c5 = c5_candidate.compute(g1)
        delta_c5 = daily_v - c5
        exact_c5 = delta_c5 == 0.0
        residual_class = classify_c5_residual(delta_c5)

        # ---- Discrimination ----
        # The C1-C4 sums above already follow the canonical board contract.
        # These legacy predicate labels did not: G4 is odd-lot, while every
        # T-board is put-through (T4/T6 are also odd-lot).
        board_quantities = {"G1": g1, "G4": g4, "T1": t1, "T3": t3, "T4": t4, "T6": t6}
        has_continuous = board_quantities["G1"] > 0
        has_put_through = any(
            board_quantities[code] > 0
            for code, meaning in DNSE_BOARD_SEMANTICS.items()
            if meaning.startswith("PUT_THROUGH")
        )
        has_odd_lot = any(
            board_quantities[code] > 0
            for code, meaning in DNSE_BOARD_SEMANTICS.items()
            if "ODD_LOT" in meaning
        )
        discriminating = has_continuous and has_put_through and has_odd_lot

        # ---- C1–C4 verdict (unchanged from original milestone) ----
        if not discriminating:
            verdict_c1_c4 = "INSUFFICIENT_DISCRIMINATION"
        elif any(exact_c1_c4.values()):
            verdict_c1_c4 = "VALIDATED_READY_FOR_P0_B2D_REVIEW"
        else:
            verdict_c1_c4 = "CONFLICTING"

        results.append(
            {
                # identity
                "symbol": symbol,
                "session_date": session_date,
                # source
                "daily_v": daily_v,
                "board_G1": g1,
                "board_G4": g4,
                "board_T1": t1,
                "board_T3": t3,
                "board_T4": t4,
                "board_T6": t6,
                # C1–C4 (preserved, NOT retrospectively hidden)
                "C1": c1,
                "C2": c2,
                "C3": c3,
                "C4": c4,
                "delta_C1": deltas_c1_c4["C1"],
                "delta_C2": deltas_c1_c4["C2"],
                "delta_C3": deltas_c1_c4["C3"],
                "delta_C4": deltas_c1_c4["C4"],
                "exact_match_C1": exact_c1_c4["C1"],
                "exact_match_C2": exact_c1_c4["C2"],
                "exact_match_C3": exact_c1_c4["C3"],
                "exact_match_C4": exact_c1_c4["C4"],
                "verdict_c1_c4": verdict_c1_c4,
                # C5 (SCALED_G1 shadow)
                "C5": c5,
                "delta_C5": delta_c5,
                "exact_match_C5": exact_c5,
                "c5_empirical_scale": c5_candidate.empirical_scale,
                "c5_scale_status": c5_candidate.scale_status.value,
                "c5_semantic_unit_interpretation": c5_candidate.semantic_unit_interpretation,
                "c5_candidate_type": c5_candidate.candidate_type.value,
                "residual_class_C5": residual_class.value,
                # discrimination
                "discriminating_session": discriminating,
                # completeness (inner join guarantees both OHLC and Trades present)
                "completeness": "COMPLETE",
                # authority boundary — C5 shadow NEVER promotes liquidity authority
                "qualified_liquidity_inputs": False,
                # lineage
                "lineage_ohlc": row.get("ohlc_observation_id"),
                "canonical_trades_source_commit": source_commit,
                "canonical_trades_lineage_status": lineage_status,
            }
        )

    return pd.DataFrame(results)
