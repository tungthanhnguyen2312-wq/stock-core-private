"""DNSE Daily Volume Composition Reconciliation — P0-B.2A-B.2B + P0-B.2B1.

Reconciles authoritative daily OHLC ``v`` against board-level Trades history
across a configurable candidate set.

Scope
-----
- C1–C4: additive board-aggregation candidates from the original P0-B.2A-B.2B
  milestone.  Their failure on the real corpus is preserved and NOT hidden.
- C5:    SCALED_G1 shadow candidate introduced by P0-B.2B1.  The scale is
  data/config-driven and does NOT assert "Trades quantity unit = 10 shares"
  as an authority claim.  ``semantic_unit_interpretation = UNKNOWN`` is
  mandatory; the scale is recorded as EMPIRICAL_CANDIDATE only.

Provenance note
---------------
The canonical Trades corpus consumed here was generated by the code at commit
``2b7b38772e16c434c8adf5288cbc46ef0f7f4c02``
(``dnse_trades_canonical_shadow.py`` on branch
``feature/trades-canonical-columnar-shadow-v1``).  That commit is NOT in the
ancestry of the current P0-B worktree main HEAD.  The lineage status is
therefore recorded as SOURCE_GENERATOR_NOT_IN_CURRENT_MAIN_ANCESTRY, which
must remain visible for any future promotion review.
"""

