# ---------------------------------------------------------------------------
# C5 / SCALED_G1 candidate contract
# ---------------------------------------------------------------------------

class CandidateType(str, Enum):
    ADDITIVE_BOARD_SUM = "ADDITIVE_BOARD_SUM"
    SCALED_G1 = "SCALED_G1"


class ScaleStatus(str, Enum):
    EMPIRICAL_CANDIDATE = "EMPIRICAL_CANDIDATE"
    VALIDATED_SHADOW = "VALIDATED_SHADOW"


@dataclass(frozen=True)
class ScaledG1Candidate:
    """Contract for a SCALED_G1 shadow candidate.

    The ``empirical_scale`` is config/data-driven.  Changing the value here
    produces a different, still-deterministic evaluation.  The scale does NOT
    assert the semantic meaning of the Trades quantity unit — that remains
    UNKNOWN and must not be silently promoted.
    """

    candidate_id: str
    candidate_type: CandidateType
    empirical_scale: float
    scale_status: ScaleStatus
    semantic_unit_interpretation: str
    evidence_source: str

    def compute(self, g1_quantity: float) -> float:
        return self.empirical_scale * g1_quantity

    def record(self) -> dict[str, Any]:
        return {
            "candidate_id": self.candidate_id,
            "candidate_type": self.candidate_type.value,
            "empirical_scale": self.empirical_scale,
            "scale_status": self.scale_status.value,
            "semantic_unit_interpretation": self.semantic_unit_interpretation,
            "evidence_source": self.evidence_source,
        }


#: The single registered C5 candidate.  ``semantic_unit_interpretation`` is
#: UNKNOWN; this is not a claim that "1 Trades unit = 10 shares".
C5_CANDIDATE = ScaledG1Candidate(
    candidate_id="C5",
    candidate_type=CandidateType.SCALED_G1,
    empirical_scale=10.0,
    scale_status=ScaleStatus.EMPIRICAL_CANDIDATE,
    semantic_unit_interpretation="UNKNOWN",
    evidence_source=(
        "p0-b2ab-zero-match-root-cause-diagnosis-v1-20260818: "
        "daily_v / board_G1_quantity clusters at exactly 10.0 "
        "across 35,164/35,231 (99.8098%) symbol-sessions "
        "over 40 retained trading dates; scale discovered from data, "
        "not from a provider unit assertion"
    ),
)


# ---------------------------------------------------------------------------
# Residual classification
# ---------------------------------------------------------------------------

class ResidualClass(str, Enum):
    POSITIVE_DELTA_MULTIPLE_OF_100 = "POSITIVE_DELTA_MULTIPLE_OF_100"
    NEGATIVE_DELTA_MINUS_4 = "NEGATIVE_DELTA_MINUS_4"
    OTHER = "OTHER"
    EXACT_MATCH = "EXACT_MATCH"  # no residual


def classify_c5_residual(delta: float) -> ResidualClass:
    """Classify a single C5 residual deterministically.

    ``delta = daily_v - C5``

    Classes
    -------
    EXACT_MATCH
        delta == 0 (no residual).
    POSITIVE_DELTA_MULTIPLE_OF_100
        delta > 0 AND delta is an exact integer multiple of 100.
        Consistent with a small number of G1 executions present in ``v``
        but absent from the canonical Trades corpus for that symbol/session.
        True root cause NOT established; prior hypothesis (Task-160 27 known
        REMAINING_FAILED units) was tested and ruled out (0/67 overlap).
    NEGATIVE_DELTA_MINUS_4
        delta == -4 exactly.
        Empirically observed on SHB and VIX only across the 40-session corpus.
        Root cause NOT established by this milestone.
    OTHER
        All remaining mismatches.  Do NOT invent an explanation.
    """
    if delta == 0.0:
        return ResidualClass.EXACT_MATCH
    if delta > 0 and delta % 100 == 0:
        return ResidualClass.POSITIVE_DELTA_MULTIPLE_OF_100
    if delta == -4.0:
        return ResidualClass.NEGATIVE_DELTA_MINUS_4
    return ResidualClass.OTHER


